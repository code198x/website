#!/usr/bin/env node
/**
 * Generate vault-data.js from content collections
 * This script runs at build time to create a static data file
 * from the actual content in the project
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';
import matter from 'gray-matter';
import { glob } from 'glob';

const __filename = fileURLToPath(import.meta.url);
const __dirname = path.dirname(__filename);
const projectRoot = path.resolve(__dirname, '..');

// Helper to format entries consistently
function formatEntry(category, filePath) {
  try {
    const content = fs.readFileSync(filePath, 'utf-8');
    const { data } = matter(content);

    // Extract slug from filename
    const filename = path.basename(filePath, path.extname(filePath));
    const slug = data.slug || filename;

    return {
      c: category,  // category (short form for smaller payload)
      n: data.name || data.title || 'Untitled',  // name
      d: data.description || '',  // description
      s: slug,  // slug
      t: data.type || 'unknown',  // type
      g: data.tags || [],  // tags
      y: data.year || 0,  // year
      st: data.status || 'available',  // status
    };
  } catch (error) {
    console.error(`Error processing ${filePath}:`, error.message);
    return null;
  }
}

async function generateVaultData() {
  console.log('🔄 Generating vault-data.js from content collections...');

  const vaultData = [];
  const contentDir = path.join(projectRoot, 'src/content');

  // Define all vault categories
  const categories = [
    'hardware', 'people', 'companies',
    'applications', 'development-tools', 'utilities',
    'games', 'demos',
    'operating-systems', 'emulators', 'programming-languages',
    'techniques', 'publications', 'events', 'groups', 'formats', 'culture'
  ];

  // Process each category
  for (const category of categories) {
    const categoryPath = path.join(contentDir, category);

    // Check if category directory exists
    if (!fs.existsSync(categoryPath)) {
      console.log(`  ⏭️  Skipping ${category} (no content)`);
      continue;
    }

    // Find all .md and .mdx files in the category
    const pattern = path.join(categoryPath, '**/*.{md,mdx}');
    const files = await glob(pattern);

    if (files.length === 0) {
      console.log(`  ⏭️  Skipping ${category} (empty)`);
      continue;
    }

    console.log(`  📁 Processing ${category}: ${files.length} files`);

    // Process each file
    for (const file of files) {
      const entry = formatEntry(category, file);
      if (entry) {
        vaultData.push(entry);
      }
    }
  }

  // Generate the JavaScript module
  const outputPath = path.join(projectRoot, 'src/data/vault-data.js');
  const jsContent = `// Auto-generated vault data from content collections
// Generated at: ${new Date().toISOString()}
// DO NOT EDIT THIS FILE MANUALLY - it will be overwritten during build

// This file is generated from the markdown/MDX files in src/content/
// To update this data, modify the source files and rebuild

export const vaultData = ${JSON.stringify(vaultData, null, 2)};

// Helper function to get entries by category
export function getEntriesByCategory(category) {
  return vaultData.filter(entry => entry.c === category);
}

// Helper function to get entry by slug and category
export function getEntry(category, slug) {
  return vaultData.find(entry => entry.c === category && entry.s === slug);
}

// Get all unique tags with counts
export function getAllTags() {
  const tagCounts = {};
  vaultData.forEach(entry => {
    if (entry.g && Array.isArray(entry.g)) {
      entry.g.forEach(tag => {
        tagCounts[tag] = (tagCounts[tag] || 0) + 1;
      });
    }
  });
  return tagCounts;
}

// Get all unique types for a category
export function getTypesForCategory(category) {
  const types = new Set();
  vaultData
    .filter(entry => entry.c === category)
    .forEach(entry => {
      if (entry.t) types.add(entry.t);
    });
  return Array.from(types);
}

// Get year range
export function getYearRange() {
  const years = vaultData
    .map(entry => entry.y)
    .filter(year => year && year > 0);

  if (years.length === 0) return { min: 1970, max: 2000 };

  return {
    min: Math.min(...years),
    max: Math.max(...years)
  };
}

// Export total count for quick access
export const totalEntries = vaultData.length;
`;

  // Ensure the data directory exists
  const dataDir = path.dirname(outputPath);
  if (!fs.existsSync(dataDir)) {
    fs.mkdirSync(dataDir, { recursive: true });
  }

  // Write the file
  fs.writeFileSync(outputPath, jsContent, 'utf-8');

  console.log(`✅ Generated vault-data.js with ${vaultData.length} entries`);
  console.log(`   Output: ${outputPath}`);
}

// Run the generator
generateVaultData().catch(error => {
  console.error('❌ Error generating vault data:', error);
  process.exit(1);
});